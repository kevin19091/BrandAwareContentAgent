"""Regenerate golden_examples.md from golden_examples.json + results/*.json.

Run after `run_evals.py` (both mock and real invocations) to refresh the
human-readable sheet:
    python3 -m evals.build_sheet
"""

import json
from pathlib import Path

EVALS_DIR = Path(__file__).parent


def load_result(example_id: str) -> dict | None:
    path = EVALS_DIR / "results" / f"{example_id}.json"
    return json.loads(path.read_text()) if path.exists() else None


def format_example(example: dict, result: dict | None) -> str:
    lines = [
        f"## {example['id']}",
        "",
        f"**Brand:** {example['brand']} ({example['tier']}-tier) · "
        f"**Scenario:** {example['scenario']} · "
        f"**Mode:** {example['mode']} · **HITL:** {example['hitl_mode']}",
        "",
        f"**Brief:** {example['brief']}",
        "",
        f"**Review focus:** {example['review_focus']}",
        "",
    ]

    if result is None:
        lines.append("_Not yet run — no result captured._")
        return "\n".join(lines)

    lines.append("**Captured output:**")
    lines.append("")
    lines.append(f"- guardrail_passed: `{result.get('guardrail_passed')}` "
                  f"({result.get('guardrail_reason', '')})")
    lines.append(f"- ingestion_source: `{result.get('ingestion_source')}`")

    strategy = result.get("strategy") or {}
    if strategy:
        lines.append(f"- strategy.big_idea: {strategy.get('big_idea', '')}")
        lines.append(f"- strategy.rationale: {strategy.get('rationale', '')}")

    content = result.get("content") or {}
    ig = content.get("instagram") or {}
    if ig:
        lines.append(f"- instagram.caption: {ig.get('caption', '')}")
        lines.append(f"- instagram.brand_alignment_note: {ig.get('brand_alignment_note', '')}")

    eval_result = result.get("eval_result") or {}
    if eval_result:
        lines.append(f"- eval_result: passed=`{eval_result.get('passed')}`, "
                      f"reason: {eval_result.get('reason', '')}")

    lines.append(f"- retry_count: `{result.get('retry_count')}`, "
                  f"escalated: `{result.get('escalated')}`")

    return "\n".join(lines)


def main():
    examples = json.loads((EVALS_DIR / "golden_examples.json").read_text())
    sections = [
        "# Golden Response Sheet",
        "",
        "Generated by `evals/build_sheet.py` from `golden_examples.json` + "
        "`results/*.json`. See `evals/README.md` for methodology and the "
        "real/mock mode split rationale. Regenerate after re-running evals.",
        "",
    ]
    for example in examples:
        result = load_result(example["id"])
        sections.append(format_example(example, result))
        sections.append("")
        sections.append("---")
        sections.append("")

    (EVALS_DIR / "golden_examples.md").write_text("\n".join(sections))
    print(f"Wrote {EVALS_DIR / 'golden_examples.md'}")


if __name__ == "__main__":
    main()
